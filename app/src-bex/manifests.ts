export type ExtensionTarget = 'chrome' | 'firefox' | 'safari'

export interface ExtensionContentScript {
  matches: string[]
  js: string[]
  run_at: 'document_start' | 'document_idle' | 'document_end'
  world?: 'MAIN' | 'ISOLATED'
}

export const EXTENSION_CONTENT_MATCHES = [
  'https://*/*',
  'http://localhost/*',
  'http://127.0.0.1/*',
]

export function buildContentScripts(
  target: ExtensionTarget = 'chrome',
): ExtensionContentScript[] {
  if (target === 'safari') {
    return [
      {
        matches: [...EXTENSION_CONTENT_MATCHES],
        js: ['content.js'],
        run_at: 'document_start',
      },
    ]
  }
  return [
    {
      matches: [...EXTENSION_CONTENT_MATCHES],
      js: ['inpage.js'],
      run_at: 'document_start',
      world: 'MAIN',
    },
    {
      matches: [...EXTENSION_CONTENT_MATCHES],
      js: ['content.js'],
      run_at: 'document_start',
      world: 'ISOLATED',
    },
  ]
}

/**
 * Toolbar/extension icons. These are transparent marks published by the brand
 * build (config/brands.json `publicIcons` -> quasar.config.js
 * brandPublicIconsPlugin). The `icons/icon-*.png` launcher icons are opaque
 * ink-on-paper squares for home screens and must not be used here: browsers
 * (Safari especially) draw them as a coloured square in the toolbar.
 */
export const EXTENSION_ICONS: Record<string, string> = {
  '16': 'icons/extension-16x16.png',
  '32': 'icons/extension-32x32.png',
  '64': 'icons/extension-64x64.png',
  '128': 'icons/extension-128x128.png',
}

/**
 * The popup is plain `index.html`: Safari does not reliably load an action
 * popup whose path carries a query string. extension-boot.js (generated by
 * scripts/build-extension.mjs) adds `?extMode=popup` to the URL before the app
 * boots, so app code still sees the mode in `location.search`.
 */
export const EXTENSION_POPUP_PATH = 'index.html'

export function buildExtensionManifest(
  target: ExtensionTarget,
  version = '0.3.0',
): Record<string, any> {
  const baseManifest: Record<string, any> = {
    manifest_version: 3,
    name: 'Frank',
    version,
    description:
      'Frank encrypted messenger, privacy pool, and dApp bridge companion',
    icons: { ...EXTENSION_ICONS },
    action: {
      default_popup: EXTENSION_POPUP_PATH,
      default_title: 'Frank',
      default_icon: { ...EXTENSION_ICONS },
    },
    content_security_policy: {
      extension_pages: "script-src 'self' 'wasm-unsafe-eval'; object-src 'self'",
    },
    host_permissions: [...EXTENSION_CONTENT_MATCHES],
    content_scripts: buildContentScripts(target),
  }

  if (target === 'chrome') {
    return {
      ...baseManifest,
      permissions: [
        'storage',
        'sidePanel',
        'activeTab',
        'scripting',
        'offscreen',
      ],
      background: {
        service_worker: 'background.js',
        type: 'module',
      },
      side_panel: {
        default_path: 'index.html?extMode=sidepanel',
      },
    }
  }

  if (target === 'firefox') {
    return {
      ...baseManifest,
      browser_specific_settings: {
        gecko: {
          id: 'frank@signet.mx',
          strict_min_version: '128.0',
        },
      },
      permissions: ['storage', 'activeTab', 'scripting'],
      background: {
        scripts: ['background.js'],
        type: 'module',
      },
      sidebar_action: {
        default_panel: 'index.html?extMode=sidebar',
        default_title: 'Frank',
        default_icon: { ...EXTENSION_ICONS },
      },
    }
  }

  if (target === 'safari') {
    return {
      ...baseManifest,
      permissions: ['storage', 'activeTab', 'scripting'],
      background: {
        service_worker: 'background.js',
      },
      web_accessible_resources: [
        {
          resources: ['inpage.js'],
          matches: ['<all_urls>'],
        },
      ],
    }
  }

  throw new Error(`Unsupported extension target: ${String(target)}`)
}
