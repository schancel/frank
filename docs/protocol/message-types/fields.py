# CDDL agreement: every shape that names a CDDL rule must declare exactly that rule's keys.

def _strip_comments(text: str) -> str:
    return "\n".join(line.split(";", 1)[0] for line in text.splitlines())


def _members(body: str) -> list[str]:
    parts, depth, cur = [], 0, []
    for ch in body:
        if ch in "{[(":
            depth += 1
        elif ch in "}])":
            depth -= 1
        if ch in ",\n" and depth == 0:
            parts.append("".join(cur).strip())
            cur = []
        else:
            cur.append(ch)
    parts.append("".join(cur).strip())
    return [p for p in parts if p]


def cddl_rules(text: str) -> dict[str, dict]:
    """Map rules `name = { ... }` → {"required": set, "optional": set, "open": bool, "inner": {...}}."""

    text = _strip_comments(text)
    rules: dict[str, dict] = {}
    for m in re.finditer(r"^([a-z0-9-]+)\s*=\s*\{", text, re.M):
        start = m.end() - 1
        depth, i = 0, start
        while i < len(text):
            if text[i] == "{":
                depth += 1
            elif text[i] == "}":
                depth -= 1
                if depth == 0:
                    break
            i += 1
        rules[m.group(1)] = _parse_map(text[start + 1 : i])
    return rules


def _parse_map(body: str) -> dict:
    required, optional, inner, open_ = set(), set(), {}, False
    for member in _members(body):
        if re.match(r"^\*\s*uint\s*=>", member):
            open_ = True
            continue
        fm = re.match(r"^(\?\s*)?(\d+)\s*:\s*(.*)$", member, re.S)
        if not fm:
            continue
        key = int(fm.group(2))
        (optional if fm.group(1) else required).add(key)
        value = fm.group(3).strip()
        if value.startswith("{") and value.endswith("}"):
            inner[key] = _parse_map(value[1:-1])
    return {"required": required, "optional": optional, "open": open_, "inner": inner}


def cddl_problems(root: Path, structs: list[Struct]) -> list[str]:
    cache: dict[str, dict[str, dict]] = {}
    problems = []
    for s in structs:
        for sh in s.shapes:
            if not sh.cddl:
                continue
            path, rule = sh.cddl.split("#", 1)
            where = f"{s.source}: {s.key}{' ' + sh.name if sh.name else ''}"
            if path not in cache:
                file = root / path
                if not file.is_file():
                    problems.append(f"{where}: CDDL file {path} not found")
                    cache[path] = {}
                    continue
                cache[path] = cddl_rules(file.read_text())
            rule_name, *inner_keys = rule.split(".")
            found = cache[path].get(rule_name)
            for k in inner_keys:
                found = found["inner"].get(int(k)) if found else None
            if found is None:
                problems.append(f"{where}: CDDL rule {sh.cddl} not found")
                continue
            req = {s.fields[n] for n in sh.required}
            opt = {s.fields[n] for n in sh.optional}
            if req != found["required"]:
                problems.append(
                    f"{where}: required keys {sorted(req)} disagree with {sh.cddl} {sorted(found['required'])}"
                )
            if opt != found["optional"]:
                problems.append(
                    f"{where}: optional keys {sorted(opt)} disagree with {sh.cddl} {sorted(found['optional'])}"
                )
            if sh.open != found["open"]:
                problems.append(f"{where}: open={sh.open} disagrees with {sh.cddl} (open={found['open']})")
    return problems


