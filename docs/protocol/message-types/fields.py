"""Frank-CBOR map field keys and enumerated values: registry loading, rendering and checks.

The registry is `docs/protocol/message-types/fields/*.json`, beside the type registry `v1.json`.
`generate.py` imports this module; see README.md beside it for the format and the commands.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path

FIELDS_DIR = Path("docs/protocol/message-types/fields")
TS_FIELDS_OUT = Path("packages/frank-codec/src/message-fields.generated.ts")
RUST_FIELDS_OUT = Path("backend/cashweb/frank-cbor/src/message_fields.rs")

NAME_RE = re.compile(r"^[a-z][a-z0-9]*(-[a-z0-9]+)*$")
U64_MAX = 0xFFFF_FFFF_FFFF_FFFF
RUST_ENUM_TYPES = {"u8", "u16", "u32", "u64", "i128"}

HEADER = [
    "GENERATED by docs/protocol/message-types/generate.py from docs/protocol/message-types/fields/.",
    "Do not edit; edit the registry and regenerate (see docs/protocol/message-types/README.md).",
]


class FieldRegistryError(Exception):
    pass


@dataclass
class Shape:
    name: str | None
    required: list[str]
    optional: list[str]
    open: bool
    cddl: str | None


@dataclass
class Struct:
    key: str
    source: str
    description: str
    fields: dict[str, int]
    shapes: list[Shape] = field(default_factory=list)


@dataclass
class Enum:
    key: str
    source: str
    description: str
    rust_type: str
    values: dict[str, int]


def camel(name: str) -> str:
    head, *rest = name.split("-")
    return head + "".join(p[:1].upper() + p[1:] for p in rest)


def upper(name: str) -> str:
    return name.upper().replace("-", "_")


def snake(name: str) -> str:
    return name.replace("-", "_")


def shape_const(struct: Struct, shape: Shape) -> str:
    return upper(struct.key) + ("_" + upper(shape.name) if shape.name else "") + "_SHAPE"


def load(root: Path) -> tuple[list[Struct], list[Enum]]:
    structs: list[Struct] = []
    enums: list[Enum] = []
    errors: list[str] = []
    names: dict[str, str] = {}
    files = sorted((root / FIELDS_DIR).glob("*.json"))
    if not files:
        raise FieldRegistryError(f"{FIELDS_DIR}: no registry files")
    for path in files:
        rel = str(path.relative_to(root))
        data = json.loads(path.read_text())
        if data.get("version") != 1:
            errors.append(f"{rel}: version must be 1")
            continue
        for raw in data.get("structs", []):
            key = raw.get("key")
            where = f"{rel}: struct {key!r}"
            if not isinstance(key, str) or not NAME_RE.match(key):
                errors.append(f"{where}: invalid key")
                continue
            if upper(key) in names:
                errors.append(f"{where}: name collides with {names[upper(key)]}")
            names[upper(key)] = where
            fields_raw = raw.get("fields")
            if not isinstance(fields_raw, dict) or not fields_raw:
                errors.append(f"{where}: fields must be a non-empty object")
                continue
            seen: dict[int, str] = {}
            for fname, fkey in fields_raw.items():
                if not NAME_RE.match(fname):
                    errors.append(f"{where}: invalid field name {fname!r}")
                if not isinstance(fkey, int) or isinstance(fkey, bool) or not 0 <= fkey <= U64_MAX:
                    errors.append(f"{where}: field {fname} key {fkey!r} is not a uint")
                    continue
                if fkey in seen:
                    errors.append(f"{where}: key {fkey} is both {seen[fkey]} and {fname}")
                seen[fkey] = fname
            struct = Struct(key, rel, raw.get("description", ""), dict(fields_raw))
            shapes_raw = raw.get("shapes", [])
            if not isinstance(shapes_raw, list):
                errors.append(f"{where}: shapes must be a list")
                shapes_raw = []
            shape_names: set[str | None] = set()
            for s in shapes_raw:
                sname = s.get("name")
                if sname is not None and not NAME_RE.match(sname):
                    errors.append(f"{where}: invalid shape name {sname!r}")
                if sname in shape_names:
                    errors.append(f"{where}: duplicate shape {sname!r}")
                shape_names.add(sname)
                req, opt = s.get("required", []), s.get("optional", [])
                for fname in [*req, *opt]:
                    if fname not in fields_raw:
                        errors.append(f"{where}: shape {sname!r} names unknown field {fname!r}")
                if len(set(req) | set(opt)) != len(req) + len(opt):
                    errors.append(f"{where}: shape {sname!r} lists a field twice")
                if not isinstance(s.get("open"), bool):
                    errors.append(f"{where}: shape {sname!r} needs a boolean open")
                cddl = s.get("cddl")
                if cddl is not None and (not isinstance(cddl, str) or "#" not in cddl):
                    errors.append(f"{where}: shape {sname!r} cddl must be 'path#rule'")
                struct.shapes.append(Shape(sname, list(req), list(opt), bool(s.get("open")), cddl))
            structs.append(struct)
        for raw in data.get("enums", []):
            key = raw.get("key")
            where = f"{rel}: enum {key!r}"
            if not isinstance(key, str) or not NAME_RE.match(key):
                errors.append(f"{where}: invalid key")
                continue
            if upper(key) in names:
                errors.append(f"{where}: name collides with {names[upper(key)]}")
            names[upper(key)] = where
            values = raw.get("values")
            if not isinstance(values, dict) or not values:
                errors.append(f"{where}: values must be a non-empty object")
                continue
            seen_v: dict[int, str] = {}
            for vname, value in values.items():
                if not NAME_RE.match(vname):
                    errors.append(f"{where}: invalid value name {vname!r}")
                if not isinstance(value, int) or isinstance(value, bool):
                    errors.append(f"{where}: {vname} = {value!r} is not an integer")
                    continue
                if value in seen_v and not raw.get("aliases", False):
                    errors.append(f"{where}: value {value} is both {seen_v[value]} and {vname}")
                seen_v[value] = vname
            rust_type = raw.get("rust_type", "u32")
            if rust_type not in RUST_ENUM_TYPES:
                errors.append(f"{where}: rust_type must be one of {sorted(RUST_ENUM_TYPES)}")
            enums.append(Enum(key, rel, raw.get("description", ""), rust_type, dict(values)))
    if errors:
        raise FieldRegistryError("\n".join(errors))
    return sorted(structs, key=lambda s: s.key), sorted(enums, key=lambda e: e.key)


def _doc(text: str) -> str:
    return " ".join(text.split())


def _ts_list(label: str, items: list[str]) -> list[str]:
    """`  label: [a, b],` laid out the way Prettier (printWidth 80) lays it out."""

    line = f"  {label}: [" + ", ".join(items) + "],"
    if len(line) <= 80:
        return [line]
    return [f"  {label}: [", *[f"    {i}," for i in items], "  ],"]


def render_ts(structs: list[Struct], enums: list[Enum]) -> str:
    out = [*(f"// {h}" for h in HEADER), ""]
    out += [
        "/** Required and optional keys of one CDDL map rule, and whether it admits additive keys. */",
        "export interface MapShape {",
        "  readonly required: readonly number[]",
        "  readonly optional: readonly number[]",
        "  readonly open: boolean",
        "}",
        "",
    ]
    for s in structs:
        const = upper(s.key)
        out.append(f"/** `{s.key}` field keys{': ' + _doc(s.description) if s.description else '.'} */")
        out.append(f"export const {const} = {{")
        out += [f"  {camel(n)}: {k}," for n, k in s.fields.items()]
        out.append("} as const")
        for sh in s.shapes:
            label = f" ({sh.cddl})" if sh.cddl else ""
            out.append(f"/** `{s.key}`{' ' + sh.name if sh.name else ''} map shape{label}. */")
            out.append(f"export const {shape_const(s, sh)}: MapShape = {{")
            out += _ts_list("required", [f"{const}.{camel(n)}" for n in sh.required])
            out += _ts_list("optional", [f"{const}.{camel(n)}" for n in sh.optional])
            out.append(f"  open: {'true' if sh.open else 'false'},")
            out.append("}")
        out.append("")
    for e in enums:
        out.append(f"/** `{e.key}` values{': ' + _doc(e.description) if e.description else '.'} */")
        out.append(f"export const {upper(e.key)} = {{")
        out += [f"  {camel(n)}: {v}," for n, v in e.values.items()]
        out.append("} as const")
        out.append("")
    return "\n".join(out)


def render_rust(structs: list[Struct], enums: list[Enum]) -> str:
    out = [
        "//! Frank-CBOR map field keys and enumerated values, one module per registered map or enum.",
        "//!",
        *(f"//! {h}" for h in HEADER),
        "",
        "/// Required and optional keys of one CDDL map rule, and whether it admits additive keys.",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub struct MapShape {",
        "    /// Keys that must be present.",
        "    pub required: &'static [u64],",
        "    /// Keys that may be present.",
        "    pub optional: &'static [u64],",
        "    /// Whether undeclared keys are retained (open) or rejected (closed).",
        "    pub open: bool,",
        "}",
        "",
    ]
    for s in structs:
        out.append(f"/// `{s.key}` field keys{': ' + _doc(s.description) if s.description else '.'}")
        out.append(f"pub mod {snake(s.key)} {{")
        if s.shapes:
            out.append("    use super::MapShape;")
            out.append("")
        out += [f"    /// Field `{n}`.\n    pub const {upper(n)}: u64 = {k};" for n, k in s.fields.items()]
        for sh in s.shapes:
            label = f" ({sh.cddl})" if sh.cddl else ""
            name = (upper(sh.name) + "_" if sh.name else "") + "SHAPE"
            out.append(f"    /// `{s.key}`{' ' + sh.name if sh.name else ''} map shape{label}.")
            out.append(f"    pub const {name}: MapShape = MapShape {{")
            out.append("        required: &[" + ", ".join(upper(n) for n in sh.required) + "],")
            out.append("        optional: &[" + ", ".join(upper(n) for n in sh.optional) + "],")
            out.append(f"        open: {'true' if sh.open else 'false'},")
            out.append("    };")
        out.append("}")
        out.append("")
    for e in enums:
        out.append(f"/// `{e.key}` values{': ' + _doc(e.description) if e.description else '.'}")
        out.append(f"pub mod {snake(e.key)} {{")
        out += [f"    /// `{n}`.\n    pub const {upper(n)}: {e.rust_type} = {v};" for n, v in e.values.items()]
        out.append("}")
        out.append("")
    return "\n".join(out).replace("\n\n\n", "\n\n")


