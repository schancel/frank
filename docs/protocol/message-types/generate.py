#!/usr/bin/env python3
"""Generate Frank-CBOR type identifier constants from docs/protocol/message-types/v1.json.

Usage (from the repository root):
    python3 docs/protocol/message-types/generate.py           # rewrite every output
    python3 docs/protocol/message-types/generate.py --check   # fail if anything is stale

See README.md beside this file for the source, the outputs and what --check enforces.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
REGISTRY = Path("docs/protocol/message-types/v1.json")
TS_OUT = Path("packages/frank-codec/src/message-types.generated.ts")
RUST_OUT = Path("backend/cashweb/frank-cbor/src/message_types.rs")
CBOR_README = Path("docs/protocol/cbor/README.md")
DOCS_SPEC = Path("packages/docs/cbor/spec.md")

BEGIN = "<!-- BEGIN GENERATED: message-types (docs/protocol/message-types/generate.py) -->"
END = "<!-- END GENERATED: message-types -->"
HEADER = [
    "GENERATED by docs/protocol/message-types/generate.py from docs/protocol/message-types/v1.json.",
    "Do not edit; edit the registry and regenerate (see docs/protocol/message-types/README.md).",
]

KEY_RE = re.compile(r"^[a-z][a-z0-9]*(-[a-z0-9]+)*$")
FAMILIES = {"directory", "delivery", "content", "topic", "proof"}
STATUSES = {"active", "proof-only"}
U32_MAX = 0xFFFF_FFFF


class RegistryError(Exception):
    pass


def load_registry() -> list[dict]:
    data = json.loads((ROOT / REGISTRY).read_text())
    if data.get("version") != 1:
        raise RegistryError(f"{REGISTRY}: version must be 1")
    types = data["types"]
    errors: list[str] = []
    seen_ids: dict[int, str] = {}
    seen_keys: set[str] = set()
    for t in types:
        key, tid = t.get("key"), t.get("id")
        if not isinstance(key, str) or not KEY_RE.match(key):
            errors.append(f"invalid key {key!r}")
            continue
        if not isinstance(tid, int) or isinstance(tid, bool) or not 0 < tid <= U32_MAX:
            errors.append(f"{key}: id {tid!r} is not a uint32 above 0")
            continue
        if tid in seen_ids:
            errors.append(f"duplicate id {tid}: {seen_ids[tid]} and {key}")
        if key in seen_keys:
            errors.append(f"duplicate key {key}")
        seen_ids[tid] = key
        seen_keys.add(key)
        if t.get("family") not in FAMILIES:
            errors.append(f"{key}: family must be one of {sorted(FAMILIES)}")
        if t.get("status") not in STATUSES:
            errors.append(f"{key}: status must be one of {sorted(STATUSES)}")
        if not isinstance(t.get("open_item_field"), bool):
            errors.append(f"{key}: open_item_field must be a boolean")
        if t.get("status") == "active" and not all(
            isinstance(t.get(f), str) and t[f] for f in ("name", "title", "schema", "rule")
        ):
            errors.append(f"{key}: an active type needs name, title, schema and rule")
    if errors:
        raise RegistryError("\n".join(f"{REGISTRY}: {e}" for e in errors))
    # Outputs list types by id, so renumbering is an edit of `id` alone.
    return sorted(types, key=lambda t: t["id"])


def const_name(t: dict) -> str:
    return "TYPE_" + t["key"].upper().replace("-", "_")


def literal(tid: int, rust: bool) -> str:
    if tid <= 0xFFFF:
        return str(tid)
    hexa = f"{tid:08x}"
    return "0x" + (f"{hexa[:4]}_{hexa[4:]}" if rust else hexa)


def comment(t: dict) -> str:
    return t["name"] + ("" if t["status"] == "active" else f" ({t['status']})") + "."


def render_ts(types: list[dict]) -> str:
    lines = [*(f"// {h}" for h in HEADER), "", "// Assigned Frank-CBOR type identifiers (docs/protocol/cbor/README.md E5).", ""]
    for t in types:
        lines.append(f"/** {comment(t)} */")
        lines.append(f"export const {const_name(t)} = {literal(t['id'], False)} as const")
    forbidden = [const_name(t) for t in types if not t["open_item_field"]]
    lines += [
        "",
        "/** Assigned types that an open message-item field cannot carry (S8). */",
        "export const OPEN_ITEM_FIELD_FORBIDDEN_TYPES: ReadonlySet<number> = new Set([",
        *[f"  {n}," for n in forbidden],
        "])",
        "",
    ]
    return "\n".join(lines)


def render_rust(types: list[dict]) -> str:
    lines = [
        "//! Assigned Frank-CBOR type identifiers (`docs/protocol/cbor/README.md` E5).",
        "//!",
        *(f"//! {h}" for h in HEADER),
        "",
    ]
    for t in types:
        lines.append(f"/// {comment(t)}")
        lines.append(f"pub const {const_name(t)}: u32 = {literal(t['id'], True)};")
    forbidden = [const_name(t) for t in types if not t["open_item_field"]]
    lines += [
        "",
        "/// Assigned types that an open message-item field cannot carry (S8).",
        f"pub const OPEN_ITEM_FIELD_FORBIDDEN_TYPES: [u32; {len(forbidden)}] = [",
        *[f"    {n}," for n in forbidden],
        "];",
        "",
    ]
    return "\n".join(lines)


def table(header: list[str], aligns: list[str], rows: list[list[str]]) -> list[str]:
    """A Markdown table padded the way Prettier pads one."""

    widths = [max(len(r[i]) for r in [header, *rows]) for i in range(len(header))]
    widths = [max(w, 3) for w in widths]

    def cell(text: str, width: int, align: str) -> str:
        pad = width - len(text)
        if align == "right":
            return " " * pad + text
        return text + " " * pad

    def rule(width: int, align: str) -> str:
        if align == "right":
            return "-" * (width - 1) + ":"
        return "-" * width

    out = ["| " + " | ".join(cell(h, w, a) for h, w, a in zip(header, widths, aligns)) + " |"]
    out.append("| " + " | ".join(rule(w, a) for w, a in zip(widths, aligns)) + " |")
    out += ["| " + " | ".join(cell(c, w, a) for c, w, a in zip(r, widths, aligns)) + " |" for r in rows]
    return out


def readme_table(types: list[dict]) -> list[str]:
    rows = []
    for t in types:
        tid = literal(t["id"], False)
        if t["schema"] is None:
            rows.append([tid, t["name"], "Opaque fixture payload"])
        else:
            rows.append([tid, t["name"], f"[{Path(t['schema']).name}]({t['schema']})"])
    return table(["Type ID", "Name", "Schema"], ["right", "left", "left"], rows)


def spec_table(types: list[dict]) -> list[str]:
    rows = [
        [f"**{t['id']}**", f"`0x{t['id']:04x}`", t["title"], f"`{t['rule']}`", t["description"]]
        for t in types
        if t["status"] == "active"
    ]
    # The docs-site table uses explicit `:---` left markers for its text columns.
    header = ["Type ID", "Hex", "Name", "CDDL Schema Rule", "Description"]
    widths = [max(max(len(r[i]) for r in [header, *rows]), 3) for i in range(len(header))]

    def center(text: str, width: int) -> str:
        pad = width - len(text)
        return " " * (pad // 2) + text + " " * (pad - pad // 2)

    def fmt(r: list[str]) -> str:
        cells = [center(r[0], widths[0]), center(r[1], widths[1])]
        cells += [r[i] + " " * (widths[i] - len(r[i])) for i in range(2, 5)]
        return "| " + " | ".join(cells) + " |"

    sep = [":" + "-" * (widths[0] - 2) + ":", ":" + "-" * (widths[1] - 2) + ":"]
    sep += [":" + "-" * (widths[i] - 1) for i in range(2, 5)]
    return [fmt(header), "| " + " | ".join(sep) + " |", *[fmt(r) for r in rows]]


def splice(path: Path, body: list[str], current: str) -> str:
    start, end = current.find(BEGIN), current.find(END)
    if start < 0 or end < start:
        raise RegistryError(f"{path}: missing the {BEGIN!r} ... {END!r} markers")
    return current[: start + len(BEGIN)] + "\n\n" + "\n".join(body) + "\n\n" + current[end:]


def outputs(types: list[dict]) -> dict[Path, str]:
    return {
        TS_OUT: render_ts(types),
        RUST_OUT: render_rust(types),
        CBOR_README: splice(CBOR_README, readme_table(types), (ROOT / CBOR_README).read_text()),
        DOCS_SPEC: splice(DOCS_SPEC, spec_table(types), (ROOT / DOCS_SPEC).read_text()),
    }


# A hand-written numeric definition of a type identifier, in TypeScript/JavaScript or Rust.
DEFINITION_RE = re.compile(
    r"\bconst\s+(?P<name>[A-Z][A-Z0-9_]*)\s*(?::\s*[A-Za-z0-9_]+\s*)?=\s*"
    r"(?P<value>0x[0-9a-fA-F_]+|[0-9][0-9_]*)\s*(?:as\s+const\s*)?[;\n]"
)
SOURCE_SUFFIXES = (".ts", ".js", ".mjs", ".cjs", ".vue", ".rs")
TEST_PATH_RE = re.compile(
    r"(^|/)(tests?|fixtures|proposals|examples|browsercheck|demo)/|\.test\.|testutil|_tests\.rs$"
)


def hand_written_ids(types: list[dict]) -> list[str]:
    """Hand-written type-id definitions that the registry should own instead.

    Every tracked source file is scanned. A definition that reuses a generated constant's name is
    an error anywhere (it shadows the registry, and may disagree with it). Outside test and fixture
    code, any `TYPE_*` constant bound to a number literal is an error: import the generated one.
    """

    by_name = {const_name(t): t["id"] for t in types}
    generated = {str(TS_OUT), str(RUST_OUT)}
    files = subprocess.run(
        ["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
        cwd=ROOT, check=True, capture_output=True, text=True,
    ).stdout.split("\0")
    problems = []
    for rel in files:
        if not rel.endswith(SOURCE_SUFFIXES) or rel in generated or "node_modules/" in rel:
            continue
        path = ROOT / rel
        if not path.is_file():
            continue
        text = path.read_text(errors="replace")
        for m in DEFINITION_RE.finditer(text):
            name, raw = m["name"], m["value"].replace("_", "")
            value = int(raw, 16) if raw.lower().startswith("0x") else int(raw)
            line = text.count("\n", 0, m.start()) + 1
            if name in by_name:
                verdict = "disagrees with" if value != by_name[name] else "duplicates"
                problems.append(f"{rel}:{line}: {name} = {value} {verdict} the registry ({by_name[name]})")
            elif name.startswith("TYPE_") and not TEST_PATH_RE.search(rel):
                problems.append(f"{rel}:{line}: hand-written type id {name} = {value}; use the generated constant")
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail instead of writing")
    args = parser.parse_args()
    try:
        types = load_registry()
        rendered = outputs(types)
    except RegistryError as e:
        print(e, file=sys.stderr)
        return 1
    stale = [p for p, text in rendered.items() if not (ROOT / p).is_file() or (ROOT / p).read_text() != text]
    if not args.check:
        for p in stale:
            (ROOT / p).write_text(rendered[p])
            print(f"wrote {p}")
    problems = hand_written_ids(types)
    if args.check and stale:
        problems = [f"{p}: stale; run python3 {Path(__file__).relative_to(ROOT)}" for p in stale] + problems
    for p in problems:
        print(p, file=sys.stderr)
    if problems:
        return 1
    if args.check:
        print(f"message types: {len(types)} registered, generated outputs current, no hand-written ids")
    return 0


if __name__ == "__main__":
    sys.exit(main())
