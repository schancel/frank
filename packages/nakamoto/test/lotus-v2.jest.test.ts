//   invalid vectors with the reference rejection reasons.
// - reference-signed-payment-v1.json, key3-one-output.json,
//   key4-two-outputs.json: tools/lotus-v2-compiler/fixtures (Lotus repository
//   b8bb21f438), P01 commitments and BIP340 signatures from the independent
