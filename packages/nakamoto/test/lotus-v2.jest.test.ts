describe('Lotus v2 addresses', () => {
  type Vectors = {
    valid: Array<{ hrp: string; root: string; address: string }>
    invalid: Array<{ address: string; reason: string }>
  }
  const vectors = fixture<Vectors>('lotus_v2_address.json')

  test('every valid vector encodes and decodes (type 0)', () => {
    for (const v of vectors.valid) {
      const chain = withAddress(v.hrp, CONSTANTS[v.hrp] as bigint)
      if (v.address === v.address.toLowerCase())
        expect(encodeLotusV2Address(chain, 0, bytes(v.root))).toBe(v.address)
      const decoded = decodeLotusV2Address(chain, v.address)
      expect(
        decoded.ok && decoded.value.type === 0 && hex(decoded.value.root),
      ).toBe(v.root)
    }
  })

  test('a descriptor checksum constant that disagrees with addresses.md is refused', () => {
    for (const chain of LOTUS_V2_CHAINS)
      expect(
        LOTUS_V2_ADDRESS_PREFIXES[chain.address.hrp]?.checksumConstant,
      ).toBe(chain.address.checksumConstant)
    const wrong = withAddress('rxpi', 0x1234n)
    const address = encodeLotusV2Address(
      LOTUS_V2_REGTEST,
      0,
      new Uint8Array(32).fill(1),
    )
    expect(() => encodeLotusV2Address(wrong, 0, new Uint8Array(32))).toThrow(
      'disagrees with addresses.md',
    )
    expect(() => decodeLotusV2Address(wrong, address)).toThrow(
      'disagrees with addresses.md',
    )
  })

  test('every invalid vector fails with the reference reason, in order', () => {
    const mainnet = withAddress('xpi', CONSTANTS.xpi as bigint)
    for (const v of vectors.invalid) {
      const decoded = decodeLotusV2Address(mainnet, v.address, [
        mainnet,
        withAddress('txpi', CONSTANTS.txpi as bigint),
      ])
      expect(decoded.ok ? 'ok' : decoded.error.code.replace(/-/g, ' ')).toBe(
        v.reason,
      )
    }
  })

  test('a regtest decoder gives the same reasons: network is checked only after a full decode', () => {
    for (const v of vectors.invalid) {
      const decoded = decodeLotusV2Address(LOTUS_V2_REGTEST, v.address)
      expect(decoded.ok ? 'ok' : decoded.error.code.replace(/-/g, ' ')).toBe(
        v.reason,
      )
    }
  })

  test('type 1 reproduces addresses.md (public scalar 1)', () => {
    const key = xOnly(1)
    expect(hex(key)).toBe(
      '79be667ef9dcbbac55a06295ce870b07029bfcdb2dce28d959f2815b16f81798',
    )
    const keyhash = lotusV2Keyhash(key)
    expect(hex(keyhash)).toBe(
      'f9f2a0b353f482f415281da3a00929d08a7d9a6498054f5ef6623b5580e607f7',
    )
    const leaf = lotusV2BranchLeaf(
      LOTUS_V2_REGTEST,
      lotusV2KeyhashProgram(keyhash),
    )
    expect(hex(leaf)).toBe(
      '84f3ac422780d391bc9210fa6e19dc8d0fd2bb1acd390e065c6a0acda9f667bb',
    )
    const address = encodeLotusV2KeyhashAddress(LOTUS_V2_REGTEST, keyhash)
    expect(address).toBe(
      'rxpi1pl8e2pv6n7jp0g9fgrk36qzff6z98mxnynqz57hhkvga4tq8xqlmsq2859j5u',
    )
    for (const text of [address, address.toUpperCase()]) {
      const decoded = decodeLotusV2Address(LOTUS_V2_REGTEST, text)
      if (!decoded.ok || decoded.value.type !== 1) throw new Error('decode')
      expect(hex(decoded.value.keyhash)).toBe(hex(keyhash))
      expect(hex(decoded.value.root)).toBe(hex(leaf))
    }
  })

  test('a well-formed address of a network with no descriptor is network-not-defined', () => {
    const mainnet = vectors.valid.find(v => v.hrp === 'xpi')!.address
    const testnet = vectors.valid.find(v => v.hrp === 'txpi')!.address
    for (const [address, network] of [
      [mainnet, 'mainnet'],
      [testnet, 'testnet'],
    ] as const) {
      expect(decodeLotusV2Address(LOTUS_V2_REGTEST, address)).toEqual({
        ok: false,
        error: { code: 'network-not-defined', network },
      })
    }
    // A broken checksum is malformed whatever the prefix.
    expect(
      decodeLotusV2Address(LOTUS_V2_REGTEST, `txpi1${'q'.repeat(61)}`),
    ).toMatchObject({
      ok: false,
      error: { code: 'bad-checksum' },
    })
  })

  test('types 2-31 do not encode', () => {
    expect(() =>
      encodeLotusV2Address(LOTUS_V2_REGTEST, 2 as 0, new Uint8Array(32)),
    ).toThrow(RangeError)
  })
})

