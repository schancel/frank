const firstArgument = (input: LotusV2Input): Uint8Array => {
  if (input.kind !== 'spend') throw new Error('spend')
  return input.witnesses[0]!.arguments[0]!
}

const hash160 = (b: Uint8Array) => ripemd160(sha256(b))

const FIXTURES = join(__dirname, 'fixtures/lotus-v2')
const fixture = <T>(name: string): T =>
  JSON.parse(readFileSync(join(FIXTURES, name), 'utf8')) as T

const hex = (bytes: Uint8Array) =>
  Array.from(bytes, b => b.toString(16).padStart(2, '0')).join('')
const bytes = (text: string) =>
  Uint8Array.from(text.match(/../g) ?? [], b => parseInt(b, 16))

/** Same format, another network: only for checking spec vectors. */
const withAddress = (
  hrp: string,
  checksumConstant: bigint,
): LotusV2ChainDescriptor => ({
  ...LOTUS_V2_REGTEST,
  address: { ...LOTUS_V2_REGTEST.address, hrp, checksumConstant },
})
const withChainId = (chainId: string): LotusV2ChainDescriptor => ({
  ...LOTUS_V2_REGTEST,
  chainId,
})
const CONSTANTS: Record<string, bigint> = {
  xpi: 0xb70061479en,
  txpi: 0xadda0f1635n,
  rxpi: 0x8172b45d63n,
}

const secret = (n: number) => {
  const out = new Uint8Array(32)
  out[31] = n
  return out
}
const schnorrSigner = (n: number, aux = new Uint8Array(32)) => {
  const key = privateKeyFromSecretBytes(secret(n), true)
  if (!key.ok) throw new Error('key')
  const signer = signingKey('schnorr', { key: key.value, aux })
  if (!signer.ok) throw new Error('signer')
  return signer.value
}
const xOnly = (n: number) => {
  const key = privateKeyFromSecretBytes(secret(n), true)
  if (!key.ok) throw new Error('key')
  const point = publicFromPrivate(key.value)
  if (!point.ok) throw new Error('point')
  return Uint8Array.from(point.value.xOnly)
}

