describe('Lotus v2 transactions (reference tool vectors)', () => {
  type Reference = {
    chain_id: string
    public_key: string
    resolved_coin: string
    wire: string
    txid: string
    txhash: string
    coins_root: string
    own_input_hash: string
    signing_message_00: string
    signing_message_01: string
    signing_message_02: string
    signature_00: string
  }
  const ref = fixture<Reference>('reference-signed-payment-v1.json')
  const chain = withChainId(ref.chain_id)

  test('parse, re-encode and identities', () => {
    const tx = decodeLotusV2Transaction(chain, bytes(ref.wire))
    expect(hex(encodeLotusV2Transaction(chain, tx))).toBe(ref.wire)
    const ids = lotusV2TransactionIdentities(chain, tx)
    expect(hex(ids.txid)).toBe(ref.txid)
    expect(hex(ids.txhash)).toBe(ref.txhash)
    const coin = decodeLotusV2Output(bytes(ref.resolved_coin))
    expect(hex(encodeLotusV2Output(coin))).toBe(ref.resolved_coin)
    expect(hex(lotusV2CoinsRoot(chain, tx, [coin]))).toBe(ref.coins_root)
    expect(hex(lotusV2OwnInputHash(chain, tx.inputs[0]!, coin))).toBe(
      ref.own_input_hash,
    )
  })

  test('the three signing messages and the FULL signature', () => {
    const tx = decodeLotusV2Transaction(chain, bytes(ref.wire))
    const coin = decodeLotusV2Output(bytes(ref.resolved_coin))
    const target = { inputIndex: 0, witnessIndex: 0 }
    expect(
      hex(lotusV2SignatureMessage(chain, tx, [coin], { ...target, mode: 0 })),
    ).toBe(ref.signing_message_00)
    expect(
      hex(lotusV2SignatureMessage(chain, tx, [coin], { ...target, mode: 1 })),
    ).toBe(ref.signing_message_01)
    expect(
      hex(lotusV2SignatureMessage(chain, tx, [coin], { ...target, mode: 2 })),
    ).toBe(ref.signing_message_02)
    const input = tx.inputs[0]!
    if (input.kind !== 'spend') throw new Error('spend')
    const operand = input.witnesses[0]!.arguments[0]!
    expect(hex(operand)).toBe(ref.signature_00)
    const key = bytes(ref.public_key)
    expect(
      verifyLotusV2Signature(chain, tx, [coin], target, operand, key),
    ).toBe(true)
    // An explicit 00 mode byte is a script error, never a FULL signature.
    const explicit = Uint8Array.from([...operand, 0])
    expect(
      verifyLotusV2Signature(chain, tx, [coin], target, explicit, key),
    ).toBe(false)
    expect(
      verifyLotusV2Signature(chain, tx, [coin], target, operand, xOnly(5)),
    ).toBe(false)
  })

  type Payment = {
    context: {
      chainId: string
      outpoint: { txid: string; index: number }
      lock: string
      coinWire: string
      outputs: Array<{
        valueAtoms: string
        branches: string[]
        paths: number[][]
      }>
    }
    valid: { wire: string; txid: string; txhash: string; message: string }
  }

  test.each([
    ['key3-one-output.json', 3],
    ['key4-two-outputs.json', 4],
  ])(
    '%s: a Frank-built spend has the vector TxID and signing message',
    (name, scalar) => {
      const v = fixture<Payment>(name)
      const c = withChainId(v.context.chainId)
      const coin = decodeLotusV2Output(bytes(v.context.coinWire))
      const lockWord = BigInt(v.context.lock)
      const signed = signLotusV2Transaction({
        chain: c,
        lock: {
          kind: Number(lockWord & 0xffn) as 0 | 1,
          value: lockWord >> 8n,
        },
        inputs: [
          {
            prevTxid: bytes(v.context.outpoint.txid),
            prevIndex: v.context.outpoint.index,
            coin,
            template: lotusV2PublicKeyTemplate(xOnly(scalar)),
            signer: schnorrSigner(scalar),
          },
        ],
        outputs: v.context.outputs.map(o => ({
          value: BigInt(o.valueAtoms),
          branches: o.branches.map(bytes),
          paths: o.paths,
        })),
      })
      // The TxID excludes witness arguments, so it matches whatever BIP340 aux the tool used.
      expect(hex(signed.txid)).toBe(v.valid.txid)
      const reference = decodeLotusV2Transaction(c, bytes(v.valid.wire))
      expect(hex(lotusV2TransactionIdentities(c, reference).txhash)).toBe(
        v.valid.txhash,
      )
      expect(
        hex(
          lotusV2SignatureMessage(c, signed.transaction, [coin], {
            inputIndex: 0,
            witnessIndex: 0,
            mode: 0,
          }),
        ),
      ).toBe(v.valid.message)
      expect(
        verifyLotusV2Signature(
          c,
          signed.transaction,
          [coin],
          { inputIndex: 0, witnessIndex: 0 },
          firstArgument(signed.transaction.inputs[0]!),
          xOnly(scalar),
        ),
      ).toBe(true)
      // BIP340 with all-zero aux reproduces the tool's signature, so the bytes are identical.
      expect(hex(signed.raw)).toBe(v.valid.wire)
    },
  )
})

describe('Lotus v2 transaction building', () => {
  const chain = LOTUS_V2_REGTEST
  const keyhashCoin = (n: number, value: bigint): LotusV2Output => ({
    value,
    branches: [
      lotusV2BranchLeaf(chain, lotusV2KeyhashTemplate(xOnly(n)).script),
    ],
    paths: [[0]],
  })

  test('keyhash spends in every mode verify, parse back and keep one TxID', () => {
    const coins = [keyhashCoin(1, 10_000_000n), keyhashCoin(3, 5_000_000n)]
    const outputs = [keyhashCoin(2, 12_000_000n), keyhashCoin(2, 2_999_000n)]
    const signed = signLotusV2Transaction({
      chain,
      inputs: coins.map((coin, i) => ({
        prevTxid: new Uint8Array(32).fill(0x11 * (i + 1)),
        prevIndex: i * 3,
        coin,
        template: lotusV2KeyhashTemplate(xOnly(i === 0 ? 1 : 3)),
        signer: schnorrSigner(i === 0 ? 1 : 3),
        mode: i === 0 ? 1 : 2,
      })),
      outputs,
    })
    const parsed = decodeLotusV2Transaction(chain, signed.raw)
    expect(encodeLotusV2Transaction(chain, parsed)).toEqual(signed.raw)
    expect(lotusV2TransactionIdentities(chain, parsed).txid).toEqual(
      signed.txid,
    )
    parsed.inputs.forEach((input, i) => {
      if (input.kind !== 'spend') throw new Error('spend')
      const [operand, key] = input.witnesses[0]!.arguments
      expect(operand!.length).toBe(65)
      expect(operand![64]).toBe(i === 0 ? 1 : 2)
      expect(
        verifyLotusV2Signature(
          chain,
          parsed,
          coins,
          { inputIndex: i, witnessIndex: 0 },
          operand!,
          key!,
        ),
      ).toBe(true)
    })
  })

  test('the planned size of a keyhash payment is its signed size', () => {
    const template = lotusV2KeyhashTemplate(xOnly(1))
    // 16-byte prefix, 181-byte FULL keyhash input, 45-byte output.
    expect(lotusV2TemplatePaymentSize(template, 1, 1)).toBe(16 + 181 + 45)
    expect(lotusV2TemplatePaymentSize(template, 1, 1, 1)).toBe(16 + 182 + 45)
    const signed = signLotusV2Transaction({
      chain,
      inputs: [1, 2, 3].map(i => ({
        prevTxid: new Uint8Array(32).fill(i),
        prevIndex: 0,
        coin: keyhashCoin(1, 1000n),
        template,
        signer: schnorrSigner(1),
      })),
      outputs: [keyhashCoin(2, 100n), keyhashCoin(3, 100n)],
    })
    expect(signed.raw.length).toBe(lotusV2TemplatePaymentSize(template, 3, 2))
  })

  test('a coin the template cannot spend is refused before signing', () => {
    expect(() =>
      signLotusV2Transaction({
        chain,
        inputs: [
          {
            prevTxid: new Uint8Array(32).fill(1),
            prevIndex: 0,
            coin: keyhashCoin(1, 1000n),
            template: lotusV2KeyhashTemplate(xOnly(2)),
            signer: schnorrSigner(2),
          },
        ],
        outputs: [keyhashCoin(1, 500n)],
      }),
    ).toThrow(LotusV2FormatError)
  })

  test('mint signature messages are explicitly unsupported', () => {
    const tx = {
      lock: { kind: 0 as const, value: 0n },
      inputs: [
        {
          kind: 'spend' as const,
          prevTxid: new Uint8Array(32).fill(1),
          prevIndex: 0,
          sequence: 0xffffffff,
          pathIndex: 0,
          witnesses: [
            { script: Uint8Array.of(0x4e), siblings: [], arguments: [] },
          ],
        },
        {
          kind: 'mint' as const,
          tokenId: new Uint8Array(32).fill(7),
          witness: { script: Uint8Array.of(0x4e), siblings: [], arguments: [] },
        },
      ],
      outputs: [],
    }
    const coin = keyhashCoin(1, 1000n)
    expect(() =>
      lotusV2SignatureMessage(chain, tx, [coin, undefined], {
        inputIndex: 1,
        witnessIndex: 0,
        mode: 0,
      }),
    ).toThrow(LotusV2UnsupportedError)
    // The grammar itself round-trips a mint input.
    const raw = encodeLotusV2Transaction(chain, tx)
    expect(
      encodeLotusV2Transaction(chain, decodeLotusV2Transaction(chain, raw)),
    ).toEqual(raw)
  })

  test('output and framing rules', () => {
    const root = new Uint8Array(32).fill(9)
    const bad: Array<[Partial<LotusV2Output>, string]> = [
      [{ branches: [] }, 'branch count'],
      [{ branches: [root, root], paths: [[0]] }, 'duplicate branch'],
      [{ paths: [] }, 'path count'],
      [{ burn: true }, 'burn paths'],
      [
        { branches: [root, new Uint8Array(32).fill(8)], paths: [[1], [0]] },
        'path order',
      ],
      [{ paths: [[1]] }, 'path index'],
      [{ tokenId: new Uint8Array(32) }, 'zero token'],
    ]
    for (const [change, reason] of bad)
      expect(() =>
        encodeLotusV2Output({
          value: 1n,
          branches: [root],
          paths: [[0]],
          ...change,
        }),
      ).toThrow(reason)
    const burn = encodeLotusV2Output({
      value: 5n,
      burn: true,
      branches: [root],
      paths: [],
    })
    expect(burn.length).toBe(43)
    expect(decodeLotusV2Output(burn)).toMatchObject({ burn: true, paths: [] })
    expect(
      encodeLotusV2Output({ value: 5n, branches: [root], paths: [[0]] }).length,
    ).toBe(45)
    expect(
      lotusV2OutputLeaf(chain, { value: 5n, branches: [root], paths: [[0]] })
        .length,
    ).toBe(32)

    const signed = signLotusV2Transaction({
      chain,
      inputs: [
        {
          prevTxid: new Uint8Array(32).fill(1),
          prevIndex: 0,
          coin: keyhashCoin(1, 1000n),
          template: lotusV2KeyhashTemplate(xOnly(1)),
          signer: schnorrSigner(1),
        },
      ],
      outputs: [keyhashCoin(1, 500n)],
    })
    expect(() =>
      decodeLotusV2Transaction(chain, Uint8Array.from([...signed.raw, 0])),
    ).toThrow('trailing bytes')
    const wrongVersion = Uint8Array.from(signed.raw)
    wrongVersion[0] = 2
    expect(() => decodeLotusV2Transaction(chain, wrongVersion)).toThrow(
      'version/lock',
    )
  })
})
